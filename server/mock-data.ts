export function semesterStart(): string {
    const now = new Date();
    // осенний семестр с 1 сентября, весенний — с 1 февраля
    const [y, m] = now.getMonth() >= 8 ? [now.getFullYear(), '09'] : now.getMonth() >= 1 ? [now.getFullYear(), '02'] : [now.getFullYear() - 1, '09'];
    return `${y}-${m}-01`;
}

